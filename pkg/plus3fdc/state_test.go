// --- mid-format -------------------------------------------------------------

// primedMidFormat stops part way through the CHRN stream of a FORMAT TRACK,
// with a staging track allocated and three of five sectors described.
func primedMidFormat(t *testing.T) *Plus3FDC {
	t.Helper()
	p := New()
	p.fdc.AttachDisk(0, loadTestDisk(t))

	tp := newTape(t, p)
	tp.seek(1)
	tp.cmd(0x4D, 0x00, 0x02, 0x05, 0x54, 0xAA) // N=2, 5 sectors, filler 0xAA
	for r := byte(1); r <= 3; r++ {
		tp.cmd(1, 0, r, 2)
	}
	return p
}

// driveFormatForward finishes the in-flight format, reads back the track it
// wrote and the untouched track next to it, then formats a different cylinder
// on the other head with a different geometry and filler — so the format
// parameters left behind differ from every captured one, and a format that
// commits to the wrong place is visible in the read-backs.
func driveFormatForward(t *testing.T, p *Plus3FDC) []byte {
	t.Helper()
	tp := newTape(t, p)

	for r := byte(4); r <= 5; r++ {
		tp.cmd(1, 0, r, 2)
	}
	tp.drain() // format result phase

	tp.cmd(0x4A, 0x00) // READ ID on the freshly formatted track
	tp.drain()
	tp.cmd(0x46, 0x00, 1, 0, 1, 2, 3, 0x2A, 0xFF) // read back sectors 1..3
	tp.drain()
	tp.cmd(0x46, 0x04, 1, 1, 1, 2, 2, 0x2A, 0xFF) // and head 1, which no format touched
	tp.drain()

	tp.seek(2)
	tp.cmd(0x46, 0x00, 2, 0, 1, 2, 2, 0x2A, 0xFF) // cylinder 2, still as the image had it
	tp.drain()

	// A second format, on the other head with a different geometry and filler.
	tp.cmd(0x4D, 0x04, 0x01, 0x03, 0x54, 0x5A)
	for r := byte(1); r <= 3; r++ {
		tp.cmd(2, 1, r, 1)
	}
	tp.drain()
	tp.cmd(0x46, 0x04, 2, 1, 1, 1, 3, 0x2A, 0xFF)
	tp.drain()
	return tp.out
}

// A FORMAT caught mid-stream holds a staging track and the CHRN bytes received
// so far, neither of which is on the disk yet and neither of which the guest
// can read back.
func TestReplayingFromMidFormatReproducesTheSameTrack(t *testing.T) {
	replayProperty(t, "mid format", primedMidFormat, driveFormatForward)
}

// --- capture hygiene --------------------------------------------------------

// A capture must not alias the live controller. The registry copies the blob
// too, but a device handing back a view of its own buffers is a bug worth
// catching here — the FDC holds a command buffer, a result buffer, a CHRN
// accumulator and a staging track, all of which keep being written as the
// controller runs.
func TestCaptureIsIndependentOfLaterChanges(t *testing.T) {
	p := primedMidFormat(t)

	st := p.SaveState()
	kept := append([]byte(nil), st...)

	driveFormatForward(t, p) // rewrites command, CHRN and staging buffers

	if !bytes.Equal(st, kept) {
		t.Errorf("the captured blob changed while the FDC carried on running: "+
			"SaveState handed back a view of live state%s", firstDiff(kept, st))
	}

	// And the blob still restores the state it was taken from.
	if err := p.LoadState(st); err != nil {
		t.Fatalf("LoadState: %v", err)
	}
	if got := driveFormatForward(t, p); len(got) == 0 {
		t.Error("restored FDC produced nothing")
	}
}

