// --- mid-read of a deleted sector -------------------------------------------

// A deleted data mark on a sector a plain READ DATA asked for stops the
// transfer at the end of that sector. The controller decided that when it found
// the sector, several hundred bytes before the transfer ends.
func TestReplayingFromMidReadOfDeletedSectorStopsInTheSamePlace(t *testing.T) {
	prime := func(t *testing.T) *Plus3FDC {
		t.Helper()
		p := New()
		p.fdc.AttachDisk(0, loadTestDisk(t))
		tp := newTape(t, p)
		tp.seek(6)
		tp.cmd(0x49, 0x00, 6, 0, 1, 2, 1, 0x2A, 0xFF) // WRITE DELETED DATA, sector 1
		tp.send(0, 512, writePattern)
		tp.drain()
		// Plain READ DATA, SK=0, over sectors 1..3. Sector 1 now carries a
		// deleted mark, so the control-mark flag is set for the whole transfer.
		tp.cmd(0x46, 0x00, 6, 0, 1, 2, 3, 0x2A, 0xFF)
		tp.readN(100)
		return p
	}
	script := func(t *testing.T, p *Plus3FDC) []byte {
		t.Helper()
		tp := newTape(t, p)
		tp.drain() // must stop after sector 1, with CM in ST2
		tp.cmd(0x46, 0x00, 6, 0, 2, 2, 2, 0x2A, 0xFF)
		tp.drain() // an ordinary sector, leaving the flag clear
		return tp.out
	}
	replayProperty(t, "mid read of a deleted sector", prime, script)
}

