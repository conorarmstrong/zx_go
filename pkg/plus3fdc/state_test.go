// --- mid-scan ---------------------------------------------------------------

// A scan carries one bit that no port exposes: whether every byte compared so
// far has met the condition. It is set on the first mismatch and only read out
// when the sector ends.
func TestReplayingFromMidScanReportsTheSameVerdict(t *testing.T) {
	prime := func(t *testing.T) *Plus3FDC {
		t.Helper()
		p := New()
		p.fdc.AttachDisk(0, loadTestDisk(t))
		tp := newTape(t, p)
		tp.seek(9)
		tp.cmd(0x45, 0x00, 9, 0, 1, 2, 1, 0x2A, 0xFF) // a known pattern to scan
		tp.send(0, 512, scanPattern)
		tp.drain()
		// SCAN EQUAL, first byte deliberately wrong: the verdict is already
		// decided, 511 bytes before the controller reports it.
		tp.cmd(0x51, 0x00, 9, 0, 1, 2, 1, 0x2A, 0xFF)
		tp.status()
		tp.cmd(scanPattern(0) + 1)
		tp.send(1, 99, scanPattern)
		return p
	}
	script := func(t *testing.T, p *Plus3FDC) []byte {
		t.Helper()
		tp := newTape(t, p)
		tp.send(100, 412, scanPattern)
		tp.drain() // must report "not satisfied"
		// A scan that does match, so the flag is left the other way round.
		tp.cmd(0x51, 0x00, 9, 0, 1, 2, 1, 0x2A, 0xFF)
		tp.send(0, 512, scanPattern)
		tp.drain()
		return tp.out
	}
	replayProperty(t, "mid scan", prime, script)
}

